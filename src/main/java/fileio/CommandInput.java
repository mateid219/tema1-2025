package fileio;

public class CommandInput {
    private String command;
    private String smell;
    private String color;
    private String sound;
    private int timestamp;
    private int timeToCharge;
    private String direction;
    private String subject;
    private String type;
    private String components;
    private double rainfall;
    private double windSpeed;
    private boolean desertStorm;
    private String season;
    private int numberOfHikers;
    private String improvementType;
    private String name;

    public final String getName() {
        return name;
    }

    public final String getType() {
        return type;
    }

    public final double getRainfall() {
        return rainfall;
    }

    public final double getWindSpeed() {
        return windSpeed;
    }

    public final int getNumberOfHikers() {
        return numberOfHikers;
    }

    public final int getTimestamp() {
        return timestamp;
    }

    public final int getTimeToCharge() {
        return timeToCharge;
    }

    public final String getColor() {
        return color;
    }

    public final String getCommand() {
        return command;
    }

    public final String getComponents() {
        return components;
    }

    public final String getDirection() {
        return direction;
    }

    public final String getImprovementType() {
        return improvementType;
    }

    public final String getSeason() {
        return season;
    }

    public final String getSmell() {
        return smell;
    }
}

